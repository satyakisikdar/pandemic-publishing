"""Item 18: generate figures_v2/figS2 (mean citedness by team size bin) and figS3 (2-yr citations by size bin).
Reads strat_if.csv / strat_cites.csv (duckdb from fe_model.parquet). Cells with n < 50 are suppressed."""
import csv, sys
OUT = '../figures'
BINS = {1: '2 authors', 2: '3--5 authors', 3: '6--10 authors', 4: '11--30 authors'}
CLS = [(0, '0p', '0p_new', 'No OS'), (50, '50p', '50p_new', 'Minority OS'), (99, '99p', '75p_new', 'Majority OS'), (100, '100p', '100p_new', 'Only OS')]
MIN_N = 50
fmt = lambda n: f'{n/1000:.1f}K' if n >= 1000 else str(n)

# ---------- figS2: boxplots of journal two-year mean citedness ----------
iff = {(int(r['bin']), int(r['wt'])): r for r in csv.DictReader(open('strat_if.csv'))}
L = [r"""% REV-2026-11 item 18: new figure -- Fig 4 stratified by team size (coauthor citation-model comment). Generated by
% analysis/make_strat_figs.py from strat_if.csv; whiskers = Fig 4 convention (Q3 + 1.5 IQR, floor at 0).
\begin{tikzpicture}
\begin{groupplot}[
  group style={group size=4 by 1, horizontal sep=8pt, yticklabels at=edge left},
  width=0.29\textwidth, height=150pt, xmin=-0.5, xmax=15, xtick distance=5,
  ymin=0.5, ymax=4.5, ytick={1,2,3,4}, yticklabels={No OS, Minority OS, Majority OS, Only OS},
  boxplot/draw direction=x, xmajorgrids, grid style={draw opacity=0.4},
  title style={font=\sffamily\small, yshift=-4pt}, tick label style={font=\sffamily\scriptsize},
  every axis plot/.append style={line width=0.5pt},
]"""]
for b, title in BINS.items():
    L.append(rf"\nextgroupplot[title={{{title}}}, xlabel={{\footnotesize Mean citedness}}]")
    for i, (wt, sty, _, name) in enumerate(CLS, 1):
        r = iff.get((b, wt))
        if r is None:
            L.append(rf"  \node[font=\sffamily\tiny, text=black!55, anchor=west] at (axis cs:0,{i}) {{not possible}};")
            continue
        n = int(r['n'])
        if n < MIN_N:
            L.append(rf"  \node[font=\sffamily\tiny, text=black!55, anchor=west] at (axis cs:0,{i}) {{n = {n}, not shown}};")
            continue
        q1, med, q3 = float(r['q1']), float(r['med']), float(r['q3'])
        iqr = q3 - q1; lo = max(0.0, q1 - 1.5 * iqr); hi = q3 + 1.5 * iqr
        L.append(rf"""  \addplot[{sty}, boxplot prepared={{lower whisker={lo:.3f}, lower quartile={q1:.3f}, median={med:.3f}, upper quartile={q3:.3f}, upper whisker={hi:.3f}, draw position={i}, box extend=0.6}}] coordinates {{}};
  \node[font=\sffamily\tiny, text=black!60, anchor=west] at (axis cs:{hi:.3f},{i}) {{\,{fmt(n)}}};""")
L.append(r"\end{groupplot}" + "\n" + r"\end{tikzpicture}")
open(f'{OUT}/figS2-citedness-by-team-size.tex', 'w').write('\n'.join(L) + '\n')

# ---------- figS3: mean two-year citations with 95% CI ----------
rows = list(csv.DictReader(open('strat_cites.csv')))
L = [r"""% REV-2026-11 item 18: new figure -- Fig 5 panel C stratified by team size (coauthor citation-model comment). Generated by
% analysis/make_strat_figs.py from strat_cites.csv; error bars = 95% normal-approximation CI (1.96 SE).
\pgfplotstableread{
bin year wt n mean ci"""]
for r in rows:
    n = int(r['n']); ok = n >= MIN_N
    L.append(f"{r['bin']} {r['y']} {r['wt']} {n} {float(r['mean']) if ok else 'nan'} {float(r['ci']) if ok else 'nan'}")
L.append(r"""}{\StratCites}
\begin{tikzpicture}
\begin{groupplot}[
  group style={group size=4 by 1, horizontal sep=8pt, yticklabels at=edge left},
  width=0.29\textwidth, height=170pt, xbar, /pgf/bar width=4pt,
  xmin=0, xmax=125, xtick distance=40, ymin=2019.6, ymax=2022.4, y dir=reverse,
  ytick={2020,2021,2022}, yticklabels={2020,2021,2022}, ytick style={draw=none}, xmajorgrids, grid style={draw opacity=0.4},
  title style={font=\sffamily\small, yshift=-4pt}, tick label style={font=\sffamily\scriptsize},
  unbounded coords=discard, error bars/x dir=both, error bars/x explicit=true,
  error bars/error bar style={line width=0.4pt, black!70}, area legend,
]""")
for b, title in BINS.items():
    opts = rf"title={{{title}}}, xlabel={{\footnotesize Mean citations (2 yrs)}}"
    if b == 1:
        opts += r", legend style={at={(0,1.13)}, anchor=south west, legend columns=4, draw=none, font=\sffamily\scriptsize, column sep=6pt}"
    L.append(rf"\nextgroupplot[{opts}]")
    if b == 1:   # legend images first, so the four entries attach to them, not to data plots (one panel lacks a series)
        for _, _, sty, name in CLS:
            L.append(rf"  \addlegendimage{{area legend, {sty}}}\addlegendentry{{{name}}}")
    for wt, _, sty, name in CLS:
        L.append(rf"  \addplot[{sty}, x filter/.expression={{and(\thisrow{{bin}}=={b}, \thisrow{{wt}}=={wt}) ? x : nan}}] table[y=year, x=mean, x error=ci] {{\StratCites}};")
L.append(r"\end{groupplot}" + "\n" + r"\end{tikzpicture}")
open(f'{OUT}/figS3-citations-by-team-size.tex', 'w').write('\n'.join(L) + '\n')
print('ok')
