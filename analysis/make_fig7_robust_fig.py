"""Writes figures_v2/figS4-collab-robustness.tex from fig7_robust.csv (items 12, 13, 15).

2x4 small multiples of Fig 7 panel C (observed minus null, pp): row 1 team-size bins, row 2
paper-weighted + per-year. Each cell prints the difference and its 95% bootstrap half-width;
the empty upper triangle carries the obs/null ratio of the three diagonal cells.
Color scale is the main figure's (+-8 pp, temp). White text below -5.7 pp: the WCAG 4.5:1 crossover
on temp at this range (white fails from -5.2 up, black fails from -5.9 down).
"""
import pandas as pd

OUT = '../figures/figS4-collab-robustness.tex'
d = pd.read_csv('fig7_robust.csv')
d['ci'] = (d['diff'] - d.diff_lo).combine(d.diff_hi - d['diff'], max)
d['ratio'] = d.obs / d['null']

# matrix positions as in fig7-collab-heatmap.tex: x = column type, y = row type, x >= y filled
POS = {'EE': (0, 0), 'EB': (1, 0), 'EN': (2, 0), 'BB': (1, 1), 'BN': (2, 1), 'NN': (2, 2)}
PANELS = [('size_bin', '2', '2 authors'), ('size_bin', '3-5', '3--5 authors'),
          ('size_bin', '6-10', '6--10 authors'), ('size_bin', '11-30', '11--30 authors'),
          ('paper_weighted', 'all', 'Each paper once'), ('year', '2020', '2020'),
          ('year', '2021', '2021'), ('year', '2022', '2022')]
LETTERS = 'ABCDEFGH'

tables, plots = [], []
for i, (view, sub, title) in enumerate(PANELS):
    p = d[(d.view == view) & (d.subset == sub)].set_index('cell')
    assert len(p) == 6, (view, sub)
    rows = ['x y diff ci']
    for x in range(3):
        for y in range(3):
            cell = next((c for c, xy in POS.items() if xy == (x, y)), None)
            rows.append(f'{x} {y} nan nan' if cell is None else
                        f"{x} {y} {p.loc[cell, 'diff']:.4f} {p.loc[cell, 'ci']:.4f}")
    name = f'\\robust{LETTERS[i]}'
    tables.append('\\pgfplotstableread{\n' + '\n'.join(rows) + '\n}{' + name + '}')
    r = p.ratio
    ratio = (f"obs/null\\\\OS {r['EE']:.2f}$\\times$\\\\Bellw. {r['BB']:.2f}$\\times$"
             f"\\\\Newc. {r['NN']:.2f}$\\times$")
    plots.append(f"""    \\nextgroupplot[title={{{LETTERS[i]}. {title}}}]
    \\addplot[matrix plot, draw=black, semithick, mesh/cols=3,
        coordinate style/.condition={{\\thisrow{{diff}}<-5.7}}{{white}}]
        table[x=x, y=y, meta=diff] {{{name}}};
    \\node[font=\\tiny\\sffamily, align=left, anchor=south west, inner sep=1.5pt]
        at (axis cs:-0.5,2.5) {{{ratio}}};""")

VSEP = 60  # gap between the panel rows; the colorbar spans both rows plus this gap
tex = f"""% REV-2026-11 items 12, 13, 15: Fig 7 panel C by team size, paper-weighted, and by year, with 95% bootstrap CIs.
% Generated by analysis/make_fig7_robust_fig.py from fig7_robust.csv -- edit the script, not this file.
\\pgfplotsset{{colormap/temp}}  % loads the colormap here; fig7's own load is local to that figure
{chr(10).join(tables)}

\\begin{{tikzpicture}}
    \\begin{{groupplot}}[
        group style={{group size=4 by 2, group name=robust, horizontal sep=6pt, vertical sep={VSEP}pt,
            xticklabels at=all, yticklabels at=edge left}},
        width=95pt, height=95pt, scale only axis,
        xmin=-0.5, xmax=2.5, ymin=-0.5, ymax=2.5, y dir=reverse,
        xtick=data, ytick=data,
        xticklabels={{OS,Bellw.,Newc.}}, yticklabels={{OS,Bellw.,Newc.}},
        xticklabel pos=top, typeset ticklabels with strut,
        tick style={{draw=none}},
        ticklabel style={{font=\\scriptsize\\sffamily}},
        title style={{font=\\small\\bfseries\\sffamily, yshift=1.3em}},
        axis background/.style={{fill=gray!10}},
        axis line style={{draw=oc-blue-8}},
        colormap name=temp, point meta min=-8, point meta max=8,
        point meta=explicit,
        unbounded coords=discard,
        visualization depends on={{\\thisrow{{ci}} \\as \\myci}},
        nodes near coords={{%
            \\pgfmathfloatparsenumber{{\\pgfplotspointmeta}}%
            \\pgfmathfloatgetflagstomacro\\pgfmathresult\\currentflags
            \\ifnum\\currentflags=3\\else
                \\pgfmathprintnumber[assume math mode=true,showpos,fixed,fixed zerofill,precision=1]{{\\pgfplotspointmeta}}\\\\[-1pt]
                {{\\tiny\\textpm\\pgfmathprintnumber[assume math mode=true,fixed,fixed zerofill,precision=1]{{\\myci}}}}%
            \\fi}},
        nodes near coords align={{anchor=center}},
        nodes near coords style={{font=\\scriptsize\\sffamily, align=center}},
    ]
{chr(10).join(plots)}
    \\end{{groupplot}}

\\begin{{scope}}[shift={{($(robust c4r1.north east)+(8pt,0pt)$)}}]
    \\pgfplotscolorbardrawstandalone[
        colorbar, point meta min=-8, point meta max=8, colormap name=temp,
        colorbar style={{width=6pt, height={2 * 95 + VSEP}pt, ytick={{-8,-4,0,4,8}},
            yticklabels={{$-$8\\%,$-$4\\%,0\\%,+4\\%,+8\\%}},
            yticklabel style={{font=\\footnotesize\\sffamily}}, yticklabel pos=right}},
    ]
\\end{{scope}}
\\end{{tikzpicture}}
"""
open(OUT, 'w').write(tex)
print('wrote', OUT)
